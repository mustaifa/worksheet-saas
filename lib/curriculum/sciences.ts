/**
 * High-school science split into its own courses: Physics, Chemistry and
 * Biology for Grades 9–12 (NGSS high-school performance expectations).
 * Every skill reuses a Science generator, so answers stay code-computed and
 * the combined Science 9–12 pages keep working unchanged alongside these.
 * Grade 9 is the first course; later grades go deeper and review.
 */
