const ch = (topic: string): Skill => ({ topic, level: "challenge" });
const L = (title: string, ...skills: Skill[]): Lesson => ({ title, skills });
const U = (title: string, domain: string, ...lessons: Lesson[]): Unit => ({ title, domain, lessons });
